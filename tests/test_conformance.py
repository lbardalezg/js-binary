"""Byte-for-byte conformance against fixtures produced by the original Node library.

The fixtures in ``tests/fixtures/conformance.json`` were generated by
``tools/generate_fixtures.mjs`` using the original ``js-binary@1.2.0`` npm
package. This test re-implements the same tagged <-> native conversion used by
the harness and asserts that the Python port produces identical bytes and
decodes back to an equivalent value.
"""

import json
import math
import re
from datetime import datetime, timezone
from pathlib import Path

from js_binary import Regex, Type

import pytest

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "conformance.json"
HEX24 = re.compile(r"^[0-9a-fA-F]{24}$")
EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)
_SPECIAL_NUMBERS = {
    "NaN": float("nan"),
    "Infinity": float("inf"),
    "-Infinity": float("-inf"),
    "-0": -0.0,
}


def _fixture():
    if not FIXTURE_PATH.exists():
        pytest.skip("conformance fixtures not generated")
    with FIXTURE_PATH.open(encoding="utf-8") as handle:
        return json.load(handle)


CASES = _fixture()["cases"] if FIXTURE_PATH.exists() else []


def tagged_to_py(tagged):
    if isinstance(tagged, list):
        return [tagged_to_py(item) for item in tagged]
    if isinstance(tagged, dict):
        if "$type" in tagged:
            kind = tagged["$type"]
            if kind == "undefined":
                return None
            if kind == "buffer":
                return bytes.fromhex(tagged["hex"])
            if kind == "date":
                return int(tagged["ms"])
            if kind == "regex":
                return Regex(tagged["source"], tagged["flags"])
            if kind == "oid":
                return tagged["hex"]
            if kind == "number":
                return _SPECIAL_NUMBERS[tagged["value"]]
            raise AssertionError("unknown tag: " + kind)
        return {key: tagged_to_py(value) for key, value in tagged.items()}
    return tagged


def _datetime_to_ms(value):
    delta = value - EPOCH
    return delta.days * 86400000 + delta.seconds * 1000 + delta.microseconds // 1000


def py_to_tagged(value):
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        if math.isnan(value):
            return {"$type": "number", "value": "NaN"}
        if math.isinf(value):
            return {"$type": "number", "value": "Infinity" if value > 0 else "-Infinity"}
        if value == 0.0 and math.copysign(1.0, value) < 0:
            return {"$type": "number", "value": "-0"}
        return value
    if isinstance(value, str):
        if HEX24.match(value):
            return {"$type": "oid", "hex": value}
        return value
    if isinstance(value, bytes):
        return {"$type": "buffer", "hex": value.hex()}
    if isinstance(value, datetime):
        return {"$type": "date", "ms": _datetime_to_ms(value)}
    if isinstance(value, Regex):
        return {"$type": "regex", "source": value.source, "flags": value.flags}
    if isinstance(value, list):
        return [py_to_tagged(item) for item in value]
    if isinstance(value, dict):
        return {key: py_to_tagged(item) for key, item in value.items()}
    raise AssertionError("cannot tag: " + repr(value))


def _normalize_decoded(tagged):
    """Collapse ``undefined`` tags to ``None`` (Python has no undefined)."""
    if isinstance(tagged, list):
        return [_normalize_decoded(item) for item in tagged]
    if isinstance(tagged, dict):
        if tagged.get("$type") == "undefined":
            return None
        return {key: _normalize_decoded(item) for key, item in tagged.items()}
    return tagged


def _equivalent(expected, actual):
    """Deep-compare decoded structures, tolerating JSON int-vs-float parsing
    and the out-of-``datetime``-range date fallback (integer milliseconds)."""
    if isinstance(expected, dict) and expected.get("$type") == "date":
        if isinstance(actual, int) and not isinstance(actual, bool):
            return actual == expected["ms"]
    if isinstance(expected, list) and isinstance(actual, list):
        return len(expected) == len(actual) and all(
            _equivalent(e, a) for e, a in zip(expected, actual)
        )
    if isinstance(expected, dict) and isinstance(actual, dict):
        return set(expected) == set(actual) and all(
            _equivalent(expected[key], actual[key]) for key in expected
        )
    if isinstance(expected, bool) or isinstance(actual, bool):
        return expected is actual
    if isinstance(expected, (int, float)) and isinstance(actual, (int, float)):
        return float(expected) == float(actual)
    return expected == actual


def _ids():
    return [case["name"] for case in CASES]


@pytest.mark.skipif(not CASES, reason="conformance fixtures not generated")
@pytest.mark.parametrize("case", CASES, ids=_ids())
def test_encode_matches_node(case):
    schema = Type(case["schema"])
    value = tagged_to_py(case["value"])
    assert schema.encode(value).hex() == case["encoded"]


@pytest.mark.skipif(not CASES, reason="conformance fixtures not generated")
@pytest.mark.parametrize("case", CASES, ids=_ids())
def test_decode_matches_node(case):
    schema = Type(case["schema"])
    decoded = schema.decode(bytes.fromhex(case["encoded"]))
    assert _equivalent(_normalize_decoded(case["decoded"]), py_to_tagged(decoded))


@pytest.mark.skipif(not CASES, reason="conformance fixtures not generated")
@pytest.mark.parametrize("case", CASES, ids=_ids())
def test_hash_matches_node(case):
    assert Type(case["schema"]).get_hash().hex() == case["hash"]
